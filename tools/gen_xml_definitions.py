#!/usr/bin/env python3
"""Generate crates/utils/src/xml/sumo_xml_definitions_gen.rs from the C++
utils/xml/SUMOXMLDefinitions.{h,cpp}.

Usage: python tools/gen_xml_definitions.py [SUMO_SRC_DIR]
SUMO_SRC_DIR defaults to $SUMO_SRC or C:/Users/karti/sumo-src/src.

Unscoped C++ enums (SumoXMLTag, SumoXMLAttr, LinkState, LaneChangeAction) become
`pub type X = i32` plus one const per enumerator (they are used as ints and bit
flags in C++); `enum class` becomes a `#[repr(i32)]` Rust enum. Enumerator names
and table strings are kept verbatim.
"""
import os
import re
import sys

UNSCOPED = {"SumoXMLTag", "SumoXMLAttr", "LinkState", "LaneChangeAction"}
# lowercase C++ names that would clash with common variable names under a glob import
RENAME = {"tags": "TAGS", "attrs": "ATTRS"}
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "crates", "utils", "src", "xml", "sumo_xml_definitions_gen.rs")
STR = r'"((?:[^"\\]|\\.)*)"'


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_enums(header):
    enums = []  # (name, scoped, [(enumerator, value)])
    for m in re.finditer(r"enum\s+(class\s+)?(\w+)\s*\{(.*?)\};", strip_comments(header), re.S):
        scoped, name, body = bool(m.group(1)), m.group(2), m.group(3)
        values, nxt = {}, 0
        items = []
        for entry in body.split(","):
            entry = entry.strip()
            if not entry:
                continue
            if "=" in entry:
                key, expr = (s.strip() for s in entry.split("=", 1))
                expr = re.sub(r"'(.)'", lambda c: str(ord(c.group(1))), expr)
                val = eval(expr, {}, dict(values))
            else:
                key, val = entry, nxt
            values[key] = val
            items.append((key, val))
            nxt = val + 1
        enums.append((name, scoped, items))
    return enums


def parse_tables(cpp):
    """Returns {table name: (element type, [(rust string expr, key)])}."""
    tables = {}
    for m in re.finditer(r"(SequentialStringBijection|StringBijection<(\w+)>)::Entry\s+SUMOXMLDefinitions::(\w+)\[\]\s*=\s*\{(.*?)\n\};", cpp, re.S):
        typ = m.group(2) or "i32"
        entries = []
        lines = m.group(4).split("\n")
        alt = None  # pending #ifndef WIN32 entry
        branch = None
        for line in lines:
            s = line.strip()
            if s.startswith("#ifndef WIN32"):
                branch = "posix"
                continue
            if s.startswith("#else"):
                branch = "win"
                continue
            if s.startswith("#endif"):
                branch = None
                continue
            code = strip_comments(s)
            em = re.match(r"\{\s*(.*?)\s*,\s*([\w:]+)\s*\}", code)
            if not em:
                continue
            text = "".join(re.findall(STR, em.group(1)))  # TL("a") + std::string("b") -> "ab"
            key = em.group(2)
            if branch == "posix":
                alt = (text, key)
                continue
            if branch == "win":
                assert alt and alt[1] == key
                entries.append(('if cfg!(windows) { "%s" } else { "%s" }' % (text, alt[0]), key))
                alt = None
                continue
            entries.append(('"%s"' % text, key))
        tables[RENAME.get(m.group(3), m.group(3))] = (typ, entries)
    return tables


def parse_bijections(cpp):
    res = []  # (name, kind, type, table, terminator, checkDuplicates)
    for m in re.finditer(r"(SequentialStringBijection|StringBijection<(\w+)>)\s+SUMOXMLDefinitions::(\w+)\(\s*SUMOXMLDefinitions::(\w+),\s*([\w:]+)(?:,\s*(false|true))?\);", cpp, re.S):
        res.append((m.group(3), m.group(1).startswith("Seq"), m.group(2), RENAME.get(m.group(4), m.group(4)), m.group(5), m.group(6) != "false"))
    return res


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SUMO_SRC", "C:/Users/karti/sumo-src/src")
    with open(os.path.join(src, "utils", "xml", "SUMOXMLDefinitions.h"), encoding="utf-8") as f:
        header = f.read()
    with open(os.path.join(src, "utils", "xml", "SUMOXMLDefinitions.cpp"), encoding="utf-8") as f:
        cpp = f.read()
    out = ["// @generated by tools/gen_xml_definitions.py from utils/xml/SUMOXMLDefinitions.{h,cpp}; do not edit",
           "use super::string_bijection::{SequentialStringBijection, StringBijection};",
           "use std::sync::LazyLock;", ""]
    for name, scoped, items in parse_enums(header):
        if scoped:
            out.append("#[repr(i32)]")
            out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]")
            out.append("pub enum %s {" % name)
            out += ["    %s = %d," % (k, v) for k, v in items]
            out.append("}")
        else:
            out.append("pub type %s = i32;" % name)
            out += ["pub const %s: %s = %d;" % (k, name, v) for k, v in items]
        out.append("")
    for tname, (typ, entries) in parse_tables(cpp).items():
        out.append("pub static %s: [(&str, %s); %d] = [" % (tname, typ, len(entries)))
        out += ["    (%s, %s)," % (s, k) for s, k in entries]
        out.append("];")
    out.append("")
    for name, seq, typ, table, term, check in parse_bijections(cpp):
        if seq:
            out.append("pub static %s: LazyLock<SequentialStringBijection> = LazyLock::new(|| SequentialStringBijection::new(&%s, %s, %s));"
                       % (name, table, term, str(check).lower()))
        else:
            out.append("pub static %s: LazyLock<StringBijection<%s>> = LazyLock::new(|| StringBijection::new(&%s, %s, %s));"
                       % (name, typ, table, term, str(check).lower()))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
