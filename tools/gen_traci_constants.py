#!/usr/bin/env python3
"""Generate crates/utils/src/traci/traci_constants.rs from libsumo/TraCIConstants.h.

Usage: python tools/gen_traci_constants.py [SUMO_SRC_DIR]
SUMO_SRC_DIR defaults to $SUMO_SRC or C:/Users/karti/sumo-src/src.

Every `TRACI_CONST int|double NAME = VALUE;` becomes `pub const NAME: i32|f64 = VALUE;`.
Names and literal values are kept verbatim (hex stays hex, negative stays negative).
A `//` comment directly above a constant becomes its doc comment.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "crates", "utils", "src", "traci", "traci_constants.rs")
DECL = re.compile(r"^TRACI_CONST\s+(int|double)\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(-?(?:0[xX][0-9a-fA-F]+|[0-9]+(?:\.[0-9]*)?))\s*;\s*$")
RUST_TYPE = {"int": "i32", "double": "f64"}


TESTS = """
#[cfg(test)]
mod tests {
    use super::*;

    // values checked against libsumo/TraCIConstants.h
    #[test]
    fn spot_check_against_cpp() {
        assert_eq!(TRACI_VERSION, 22);
        assert_eq!(CMD_SIMSTEP, 0x02);
        assert_eq!(CMD_CLOSE, 0x7F);
        assert_eq!(DEPARTFLAG_TRIGGERED, -1);
        assert_eq!(DEPARTFLAG_LANE_FIRST_ALLOWED, -6);
        assert_eq!(INVALID_INT_VALUE, -1_073_741_824);
        assert_eq!(INVALID_DOUBLE_VALUE, -1_073_741_824.0);
        assert_eq!(VAR_SHADOW_LANE_ID, 0x9d);
    }
}
""".split("\n")[1:-1]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SUMO_SRC", "C:/Users/karti/sumo-src/src")
    path = os.path.join(src, "libsumo", "TraCIConstants.h")
    lines = open(path, encoding="utf8").read().splitlines()
    out = [
        "//! Port of libsumo/TraCIConstants.h",
        "// @generated by tools/gen_traci_constants.py from libsumo/TraCIConstants.h; do not edit",
        "",
    ]
    count = 0
    pending_doc = []
    for line in lines:
        s = line.strip()
        if s.startswith("//"):
            # banner lines (asterisks, '=') end a section and drop the section title
            text = s[2:].strip()
            if re.fullmatch(r"[*=\-/]*", text):
                pending_doc = []
            else:
                pending_doc.append(text)
            continue
        m = DECL.match(s)
        if m is None:
            if s:
                pending_doc = []
            continue
        typ, name, value = m.group(1), m.group(2), m.group(3)
        if typ == "double" and "." not in value:
            raise SystemExit(f"double constant without decimal point: {name} = {value}")
        if typ == "int":
            # reject anything that does not fit i32 (C++ int) so the literal is not silently wrapped
            v = int(value, 16) if value.lstrip("-").lower().startswith("0x") else int(value)
            if not -2**31 <= v < 2**31:
                raise SystemExit(f"int constant out of i32 range: {name} = {value}")
        for d in pending_doc:
            out.append(f"/// {d}")
        out.append(f"pub const {name}: {RUST_TYPE[typ]} = {value};")
        pending_doc = []
        count += 1
    if count == 0:
        raise SystemExit(f"no TRACI_CONST declarations found in {path}")
    out += TESTS
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {count} constants to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
